// Regenerates crates/server/src/emoji.tsv (chat emoji shortcodes) from the gemoji dataset.
//
// Source: github/gemoji, db/emoji.json, MIT License, Copyright (c) GitHub, Inc.
// Usage: node tools/emoji/gen.mjs [path/to/emoji.json]
// Without a path the dataset is fetched from the gemoji master branch.
//
// Output: one `alias<TAB>emoji` line per alias, sorted by alias. Skin-tone
// modifier variants are not in the dataset, so every row is a base emoji.

import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const SOURCE = "https://raw.githubusercontent.com/github/gemoji/master/db/emoji.json";
const here = dirname(fileURLToPath(import.meta.url));
const outFile = join(here, "../../crates/server/src/emoji.tsv");

const input = process.argv[2];
let raw;
if (input) {
  raw = await readFile(input, "utf8");
} else {
  const res = await fetch(SOURCE);
  if (!res.ok) throw new Error(`fetch ${SOURCE}: HTTP ${res.status}`);
  raw = await res.text();
}

const rows = new Map();
for (const entry of JSON.parse(raw)) {
  if (typeof entry.emoji !== "string" || !Array.isArray(entry.aliases)) {
    throw new Error(`malformed entry: ${JSON.stringify(entry)}`);
  }
  for (const alias of entry.aliases) {
    if (!/^[a-z0-9_+-]+$/.test(alias)) throw new Error(`unexpected alias: ${alias}`);
    if (rows.has(alias)) throw new Error(`duplicate alias: ${alias}`);
    rows.set(alias, entry.emoji);
  }
}

const header = [
  "# Chat emoji shortcodes: alias<TAB>emoji, one per line. Lookup is case-insensitive.",
  "# Generated by tools/emoji/gen.mjs from github/gemoji (db/emoji.json).",
  "# gemoji is MIT licensed, Copyright (c) GitHub, Inc.",
];
const body = [...rows.keys()].sort().map((alias) => `${alias}\t${rows.get(alias)}`);
await writeFile(outFile, [...header, ...body].join("\n") + "\n");
console.log(`wrote ${rows.size} aliases to ${outFile}`);
