// Regenerates client/src/profanity-words.ts from the English LDNOOBW list.
//
// Source: LDNOOBW/List-of-Dirty-Naughty-Obscene-and-Otherwise-Bad-Words, file `en`,
// licensed CC BY 4.0 (https://creativecommons.org/licenses/by/4.0/).
// Usage: node tools/profanity/gen.mjs [path/to/en]
// Without a path the list is fetched from the LDNOOBW master branch.
//
// Entries the matcher cannot produce (anything other than letters, digits, `&`,
// `$`, `@` and single spaces between words) are dropped and listed on stderr.

import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const SOURCE = "https://raw.githubusercontent.com/LDNOOBW/List-of-Dirty-Naughty-Obscene-and-Otherwise-Bad-Words/master/en";
const here = dirname(fileURLToPath(import.meta.url));
const outFile = join(here, "../../client/src/profanity-words.ts");

const input = process.argv[2];
let raw;
if (input) {
  raw = await readFile(input, "utf8");
} else {
  const res = await fetch(SOURCE);
  if (!res.ok) throw new Error(`fetch ${SOURCE}: HTTP ${res.status}`);
  raw = await res.text();
}

const matchable = /^[\p{L}\p{N}@$&]+( [\p{L}\p{N}@$&]+)*$/u;
const words = [];
const seen = new Set();
for (const line of raw.split("\n")) {
  const word = line.trim().toLowerCase();
  if (!word || seen.has(word)) continue;
  seen.add(word);
  if (matchable.test(word)) words.push(word);
  else console.error(`dropped (not matchable): ${JSON.stringify(word)}`);
}

const perLine = 6;
const lines = [];
for (let i = 0; i < words.length; i += perLine) {
  lines.push(`  ${words.slice(i, i + perLine).map((w) => JSON.stringify(w)).join(", ")},`);
}

const source = [
  "// Generated by tools/profanity/gen.mjs. Do not edit by hand.",
  "// Word list: LDNOOBW \"List-of-Dirty-Naughty-Obscene-and-Otherwise-Bad-Words\" (English).",
  "// Licence: CC BY 4.0, https://creativecommons.org/licenses/by/4.0/",
  "",
  "export const PROFANITY_WORDS: readonly string[] = [",
  ...lines,
  "];",
  "",
].join("\n");
await writeFile(outFile, source);
console.log(`wrote ${words.length} entries to ${outFile}`);
